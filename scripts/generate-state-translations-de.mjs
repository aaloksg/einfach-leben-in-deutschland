import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')

const RAW_PATH = path.join(__dirname, 'output/state-questions-raw.json')
const OUT_PATH = path.join(root, 'src/locales/de-state.ts')

function cleanText(text) {
  return text
    .replace(/\s+/g, ' ')
    .replace(/B\s+ild/g, 'Bild')
    .trim()
}

function main() {
  const raw = JSON.parse(fs.readFileSync(RAW_PATH, 'utf8'))

  const questions = {}
  for (const q of raw.questions) {
    questions[`question_${q.questionNumber}`] = {
      question: cleanText(q.question),
      answer_a: cleanText(q.options[0]),
      answer_b: cleanText(q.options[1]),
      answer_c: cleanText(q.options[2]),
      answer_d: cleanText(q.options[3])
    }
  }

  const content =
    `// Auto-generated by scripts/generate-state-translations-de.mjs from scripts/output/state-questions-raw.json.\n` +
    `export default ${JSON.stringify({ questions }, null, 2)}\n`

  fs.writeFileSync(OUT_PATH, content)
  console.log(`Wrote state DE translations to ${path.relative(root, OUT_PATH)}`)
}

main()

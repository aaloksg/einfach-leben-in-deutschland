import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')

const RAW_STATE_PATH = path.join(__dirname, 'output/state-questions-raw.json')
const STATE_DATA_OUT = path.join(root, 'src/data/state-question-answer-key.ts')

const letters = ['a', 'b', 'c', 'd']

function main() {
  const raw = JSON.parse(fs.readFileSync(RAW_STATE_PATH, 'utf8'))
  const questions = raw.questions
  const ranges = raw.stateRanges

  const entries = questions.map((q) => ({
    questionNumber: q.questionNumber,
    question: q.question,
    ...(q.questionImage ? { questionImage: q.questionImage } : {}),
    answer: null,
    answerOptions: {
      a: { value: 'a', text: q.options[0] },
      b: { value: 'b', text: q.options[1] },
      c: { value: 'c', text: q.options[2] },
      d: { value: 'd', text: q.options[3] }
    }
  }))

  const answerMap = {}
  for (const q of questions) {
    answerMap[q.questionNumber] = null
  }

  const stateOptionItems = Object.entries(ranges).map(([code, info]) => ({
    code,
    label: info.stateName
  }))

  const header =
    `import type { AnswerValue, GermanStateCode, QuestionAnswerEntry } from '../../types/question-answer-key'\n\n` +
    `// Auto-generated by scripts/extract-state-questions.mjs + scripts/generate-state-data.mjs.\n` +
    `// Fill STATE_QUESTION_ANSWER_KEY once official answer mappings are available.\n\n`

  const content =
    `${header}` +
    `export const GENERAL_QUESTION_RANGE = { start: 1, end: 300 } as const\n\n` +
    `export const STATE_QUESTION_RANGES: Record<GermanStateCode, { stateName: string; start: number; end: number; imageFolder: string }> = ${JSON.stringify(ranges, null, 2)}\n\n` +
    `export const STATE_OPTION_ITEMS: Array<{ code: GermanStateCode; label: string }> = ${JSON.stringify(stateOptionItems, null, 2)}\n\n` +
    `export const STATE_QUESTION_ANSWER_KEY: Record<number, AnswerValue | null> = ${JSON.stringify(answerMap, null, 2)}\n\n` +
    `export const stateSpecificQuestions: QuestionAnswerEntry[] = ${JSON.stringify(entries, null, 2)}\n`

  fs.mkdirSync(path.dirname(STATE_DATA_OUT), { recursive: true })
  fs.writeFileSync(STATE_DATA_OUT, content)

  console.log(`Wrote ${entries.length} state-specific questions to ${path.relative(root, STATE_DATA_OUT)}`)
}

main()
